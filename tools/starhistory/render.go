package main

import (
	"encoding/base64"
	"fmt"
	"math"
	"sort"
	"strconv"
	"strings"
	"time"
)

// RenderOptions controls the generated chart and its embedded artwork.
type RenderOptions struct {
	Repo           string
	History        []WeeklyPoint
	BackgroundData []byte
	LogoData       []byte
	RefreshedAt    time.Time
}

const (
	chartWidth  = 1200
	chartHeight = 640
	plotLeft    = 100
	plotTop     = 135
	plotWidth   = 1020
	plotHeight  = 370
)

// RenderSVG creates a self-contained SVG so README renderers do not need a
// second network request for the background image.
func RenderSVG(opts RenderOptions) string {
	history := append([]WeeklyPoint(nil), opts.History...)
	sort.Slice(history, func(i, j int) bool { return history[i].Date.Before(history[j].Date) })
	maxCount := 1
	if len(history) > 0 && history[len(history)-1].Count > maxCount {
		maxCount = history[len(history)-1].Count
	}
	maxY := niceCeiling(maxCount)
	refreshedAt := opts.RefreshedAt.UTC()
	if refreshedAt.IsZero() {
		refreshedAt = time.Now().UTC()
	}

	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">`, chartWidth, chartHeight, chartWidth, chartHeight)
	b.WriteString("\n<!-- Generated by wails-star-history (tools/starhistory) -->\n")
	b.WriteString(svgDefs())
	if len(opts.BackgroundData) > 0 {
		encoded := base64.StdEncoding.EncodeToString(opts.BackgroundData)
		fmt.Fprintf(&b, `<image href="data:image/webp;base64,%s" x="0" y="0" width="%d" height="%d" preserveAspectRatio="xMidYMid slice" opacity="0.24"/>`, encoded, chartWidth, chartHeight)
	}
	b.WriteString(`<rect width="1200" height="640" fill="url(#veil)"/>`)
	b.WriteString(`<rect x="16" y="16" width="1168" height="608" rx="28" fill="none" stroke="#ff5364" stroke-opacity="0.28"/>`)

	current := 0
	firstDate := refreshedAt
	if len(history) > 0 {
		current = history[len(history)-1].Count
		firstDate = history[0].Date
	}
	fmt.Fprintf(&b, `<title>Wails star history — %s stars</title>`, formatCount(current))
	b.WriteString(`<text x="72" y="88" class="title">Stargazers over time</text>`)
	if len(opts.LogoData) > 0 {
		encoded := base64.StdEncoding.EncodeToString(opts.LogoData)
		fmt.Fprintf(&b, `<image href="data:image/svg+xml;base64,%s" x="910" y="49" width="210" height="51" preserveAspectRatio="xMidYMid meet" opacity="0.94"/>`, encoded)
	}

	b.WriteString(`<g class="grid">`)
	for i := 0; i <= 4; i++ {
		y := plotTop + plotHeight - float64(i)*plotHeight/4
		value := maxY * i / 4
		fmt.Fprintf(&b, `<line x1="%d" y1="%s" x2="%d" y2="%s"/>`, plotLeft, number(y), plotLeft+plotWidth, number(y))
		fmt.Fprintf(&b, `<text x="%d" y="%s" text-anchor="end" class="axis-label">%s</text>`, plotLeft-18, number(y+4), formatAxisCount(value))
	}
	b.WriteString(`</g>`)

	if len(history) == 0 {
		b.WriteString(`<text x="600" y="350" text-anchor="middle" class="empty">No stargazer history available yet</text>`)
	} else {
		linePath, areaPath := chartPaths(history, maxY)
		fmt.Fprintf(&b, `<path d="%s" fill="none" stroke="#ff5364" stroke-width="14" stroke-linecap="round" stroke-linejoin="round" opacity="0.22" filter="url(#glow)"/>`, linePath)
		fmt.Fprintf(&b, `<path d="%s" fill="url(#chartFill)"/>`, areaPath)
		fmt.Fprintf(&b, `<path d="%s" fill="none" stroke="#ff5364" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>`, linePath)
		last := history[len(history)-1]
		lastX, lastY := chartPoint(len(history)-1, len(history), last.Count, maxY)
		fmt.Fprintf(&b, `<circle cx="%s" cy="%s" r="16" fill="#ff5364" opacity="0.20" filter="url(#glow)"/>`, number(lastX), number(lastY))
		fmt.Fprintf(&b, `<circle cx="%s" cy="%s" r="7" fill="#fff4f5" stroke="#ff5364" stroke-width="4"/>`, number(lastX), number(lastY))
		fmt.Fprintf(&b, `<text x="%s" y="%s" class="callout">%s</text>`, number(lastX-10), number(lastY-24), formatCount(last.Count))
	}

	for i := 0; i < 6; i++ {
		index := 0
		if len(history) > 1 {
			index = int(math.Round(float64(len(history)-1) * float64(i) / 5))
		}
		x, _ := chartPoint(index, maxInt(len(history), 1), 0, maxY)
		date := refreshedAt
		if len(history) > 0 {
			date = history[index].Date
		}
		fmt.Fprintf(&b, `<text x="%s" y="%d" text-anchor="middle" class="axis-label">%s</text>`, number(x), plotTop+plotHeight+38, date.Format("Jan '06"))
	}
	fmt.Fprintf(&b, `<text x="%d" y="%d" class="footer">First star %s</text>`, plotLeft, chartHeight-42, firstDate.Format("02 Jan 2006"))
	fmt.Fprintf(&b, `<text x="%d" y="%d" text-anchor="end" class="footer">Updated %s  ·  github.com/%s</text>`, plotLeft+plotWidth, chartHeight-42, refreshedAt.Format("02 Jan 2006"), xmlEscape(opts.Repo))
	b.WriteString("</svg>\n")
	return b.String()
}

// svgDefs returns the gradients, filter, and typography shared by the chart.
func svgDefs() string {
	return `<defs>
<linearGradient id="veil" x1="0" y1="0" x2="1" y2="1">
  <stop offset="0" stop-color="#050615" stop-opacity="0.84"/>
  <stop offset="0.55" stop-color="#100518" stop-opacity="0.72"/>
  <stop offset="1" stop-color="#05030f" stop-opacity="0.88"/>
</linearGradient>
<linearGradient id="chartFill" x1="0" y1="0" x2="0" y2="1">
  <stop offset="0" stop-color="#ff5364" stop-opacity="0.34"/>
  <stop offset="1" stop-color="#ff5364" stop-opacity="0.01"/>
</linearGradient>
<filter id="glow" x="-40%" y="-40%" width="180%" height="180%">
  <feGaussianBlur stdDeviation="9"/>
</filter>
</defs>
<style>
text { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; fill: #fff4f5; }
.title { font-family: Haettenschweiler, 'Arial Narrow', 'Nimbus Sans Narrow', 'Liberation Sans Narrow', Impact, sans-serif; font-size: 42px; font-weight: 600; letter-spacing: 0.4px; }
.grid line { stroke: #ffd9dd; stroke-opacity: 0.14; stroke-dasharray: 3 9; }
.axis-label { font-size: 22px; fill: #eabdc2; }
.callout { font-size: 20px; font-weight: 700; fill: #fff4f5; }
.empty { font-size: 22px; fill: #eabdc2; }
.footer { font-size: 18px; fill: #ca9da3; }
</style>
`
}

// chartPaths builds the line and closed area paths for the weekly history.
func chartPaths(history []WeeklyPoint, maxY int) (string, string) {
	points := make([]string, 0, len(history))
	for i, point := range history {
		x, y := chartPoint(i, len(history), point.Count, maxY)
		if i == 0 {
			points = append(points, fmt.Sprintf("M %s %s", number(x), number(y)))
		} else {
			points = append(points, fmt.Sprintf("L %s %s", number(x), number(y)))
		}
	}
	line := strings.Join(points, " ")
	firstX, _ := chartPoint(0, len(history), 0, maxY)
	lastX, _ := chartPoint(len(history)-1, len(history), 0, maxY)
	baseY := float64(plotTop + plotHeight)
	area := fmt.Sprintf("%s L %s %s L %s %s Z", line, number(lastX), number(baseY), number(firstX), number(baseY))
	return line, area
}

// chartPoint maps a history value to its position in the plot area.
func chartPoint(index, count, value, maxY int) (float64, float64) {
	progress := 0.0
	if count > 1 {
		progress = float64(index) / float64(count-1)
	}
	x := float64(plotLeft) + progress*float64(plotWidth)
	y := float64(plotTop+plotHeight) - float64(value)/float64(maxY)*float64(plotHeight)
	return x, y
}

// niceCeiling rounds a chart maximum up to a readable grid boundary.
func niceCeiling(value int) int {
	if value <= 1 {
		return 4
	}
	power := 1
	for value/power >= 10 {
		power *= 10
	}
	for _, step := range []int{1, 2, 5, 10} {
		candidate := step * power
		if candidate >= value {
			return candidate
		}
	}
	return 10 * power
}

// formatCount renders an exact star count with thousands separators.
func formatCount(value int) string {
	return formatWithCommas(value)
}

// formatAxisCount abbreviates thousands for compact y-axis labels.
func formatAxisCount(value int) string {
	if value < 1000 {
		return strconv.Itoa(value)
	}
	if value%1000 == 0 {
		return fmt.Sprintf("%dk", value/1000)
	}
	return fmt.Sprintf("%.1fk", float64(value)/1000)
}

// formatWithCommas inserts thousands separators into an integer.
func formatWithCommas(value int) string {
	negative := value < 0
	if negative {
		value = -value
	}
	s := strconv.Itoa(value)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	if negative {
		return "-" + s
	}
	return s
}

// number formats an SVG coordinate with at most two decimal places.
func number(value float64) string {
	return strconv.FormatFloat(math.Round(value*100)/100, 'f', -1, 64)
}

// maxInt returns the greater of two integers.
func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

// xmlEscape escapes text before interpolating it into SVG markup.
func xmlEscape(value string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&apos;").Replace(value)
}
