func TestProfileIsACompleteBuildRequest(t *testing.T) {
	root := t.TempDir()
	writeManifest(t, root, minimalHCL+`
profile "release" {
  target "windows/amd64" {
    formats = ["nsis"]
    sign = true
  }
  target "darwin/universal" {
    formats = ["dmg"]
    sign = true
    notarize = true
  }
}`)
	loaded, err := Load(root, "release")
	require.NoError(t, err)
	require.Equal(t, "release", loaded.Config.Selected.Name)
	require.Len(t, loaded.Config.Selected.Targets, 2)
	assert.Equal(t, []string{"dmg"}, loaded.Config.Selected.Targets[1].Formats)
}

