func TestEjectCreatesAnInactiveSibling(t *testing.T) {
	root := t.TempDir()
	writeManifest(t, root, minimalHCL)
	require.NoError(t, Eject(root, "", "v3.0.0", false))
	data, err := os.ReadFile(filepath.Join(root, EjectedFilename))
	require.NoError(t, err)
	assert.Contains(t, string(data), "Generated by Wails CLI v3.0.0")
	assert.FileExists(t, filepath.Join(root, Filename))
	_, err = LoadFile(root, filepath.Join(root, EjectedFilename), "")
	require.NoError(t, err)
	original := append([]byte(nil), data...)
	require.ErrorContains(t, Eject(root, "", "v3.0.0", false), "--force")
	after, err := os.ReadFile(filepath.Join(root, EjectedFilename))
	require.NoError(t, err)
	assert.Equal(t, original, after)

	require.NoError(t, Eject(root, "", "v3.0.1", true))
	replaced, err := os.ReadFile(filepath.Join(root, EjectedFilename))
	require.NoError(t, err)
	assert.Contains(t, string(replaced), "Generated by Wails CLI v3.0.1")
	assert.NotEqual(t, original, replaced)
}

