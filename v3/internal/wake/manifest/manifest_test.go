func writeManifest(t *testing.T, root, contents string) string {
	t.Helper()
	path := filepath.Join(root, Filename)
	require.NoError(t, os.WriteFile(path, []byte(contents), 0o644))
	return path
}

const minimalHCL = `version = 3

project {
  name = "hello"
  product_name = "Hello"
  identifier = "com.example.hello"
  version = "0.1.0"
}

frontend {
  directory = "frontend"
  install = ["pnpm", "install", "--frozen-lockfile"]
  build = ["pnpm", "run", "build"]
  dev = ["pnpm", "run", "dev"]
  output = "frontend/dist"
}

build {
  output = "bin"
}
`

func TestLoadHCLConfiguration(t *testing.T) {
	root := t.TempDir()
	writeManifest(t, root, minimalHCL)
	loaded, err := Load(root, "")
	require.NoError(t, err)
	assert.Equal(t, root, loaded.Config.Root)
	assert.Equal(t, "hello", loaded.Config.Project.BinaryName)
	assert.Equal(t, "pnpm", loaded.Config.Frontend.PackageManager)
	assert.Equal(t, []string{"pnpm", "install", "--frozen-lockfile"}, loaded.Config.Frontend.Install)
	assert.Equal(t, "frontend/dist", loaded.Config.Frontend.OutputDirectory)
	assert.Equal(t, "bin", loaded.Config.Build.OutputDirectory)
}

func TestVersionIsTheFirstAttribute(t *testing.T) {
	root := t.TempDir()
	writeManifest(t, root, `project { name = "hello" }
version = 3`)
	_, err := Load(root, "")
	require.ErrorContains(t, err, "version must be the first attribute")
}

