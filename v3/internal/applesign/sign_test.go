func TestThinAndUniversalSigning(t *testing.T) {
	for _, arch := range []string{"amd64", "arm64", "universal"} {
		t.Run(arch, func(t *testing.T) {
			work := t.TempDir()
			input := filepath.Join(work, "input")
			output := filepath.Join(work, "signed")
			if arch == "universal" {
				if err := universalbinary.Create(input, []string{"testdata/amd64.macho", "testdata/arm64.macho"}); err != nil {
					t.Fatal(err)
				}
			} else {
				writeTest(t, input, fixture(t, arch+".macho"))
			}
			before, err := os.ReadFile(input)
			if err != nil {
				t.Fatal(err)
			}
			ids, err := SignMachO(context.Background(), input, output, Options{Identifier: "org.wails.probe", Entitlements: fixture(t, "runtime.plist"), HardenedRuntime: true})
			if err != nil {
				t.Fatal(err)
			}
			want := 1
			if arch == "universal" {
				want = 2
			}
			if len(ids) != want {
				t.Fatalf("identities=%v", ids)
			}
			got, err := Inspect(output)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != len(ids) {
				t.Fatal(got)
			}
			for i := range ids {
				if got[i] != ids[i] {
					t.Fatalf("inspect=%v signed=%v", got, ids)
				}
			}
			after, _ := os.ReadFile(input)
			if !bytes.Equal(before, after) {
				t.Fatal("input modified")
			}
			verifyNative(t, output, false)
			data, err := os.ReadFile(output)
			if err != nil {
				t.Fatal(err)
			}
			if err := checkPageHashes(data); err != nil {
				t.Fatal(err)
			}
			parts, err := readSlices(bytes.NewReader(data), int64(len(data)))
			if err != nil {
				t.Fatal(err)
			}
			data[parts[0].offset+4096] ^= 1
			if err := checkPageHashes(data); err == nil {
				t.Fatal("mutated code page was accepted")
			}
			writeTest(t, output, data)
			rejectNative(t, output, false)
		})
	}
}

// This test oracle recomputes stored page hashes from bytes; it does not call
// the code-directory writer or use its returned identities.
func checkPageHashes(data []byte) error {
	parts, err := readSlices(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return err
	}
	for _, part := range parts {
		image := data[part.offset : part.offset+part.size]
		le, be := binary.LittleEndian, binary.BigEndian
		var offset uint32
		for i, pos := uint32(0), 32; i < le.Uint32(image[16:]); i++ {
			cmd, n := le.Uint32(image[pos:]), int(le.Uint32(image[pos+4:]))
			if cmd == 0x1d {
				offset = le.Uint32(image[pos+8:])
			}
			pos += n
		}
		if offset == 0 {
			return errors.New("no signature")
		}
		blob := image[offset:]
		dirOff := be.Uint32(blob[16:])
		d := blob[dirOff:]
		hashOffset, count, limit := be.Uint32(d[16:]), be.Uint32(d[28:]), be.Uint32(d[32:])
		page := uint32(1) << d[39]
		for i := uint32(0); i < count; i++ {
			sum := sha256.Sum256(image[i*page : min((i+1)*page, limit)])
			if !bytes.Equal(sum[:], d[hashOffset+i*32:hashOffset+(i+1)*32]) {
				return errors.New("page digest differs")
			}
		}
	}
	return nil
}

