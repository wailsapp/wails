// Package codesignature reads integrity-protected signing identities and creates
// CMS/PKCS#7 signatures using Go's standard cryptographic primitives.
package codesignature

import (
	"bytes"
	"context"
	"crypto"
	"crypto/rand"
	"crypto/sha256"
	"crypto/x509/pkix"
	"encoding/asn1"
	"errors"
	"math/big"
)

var (
	oidSignedData    = asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 7, 2}
	oidContentType   = asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 9, 3}
	oidMessageDigest = asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 9, 4}
	oidRSA           = asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 1, 1}
	oidRFC3161       = asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 9, 16, 2, 14}
)

type Attribute struct {
	Type   asn1.ObjectIdentifier
	Values []asn1.RawValue `asn1:"set"`
}
type issuerSerial struct {
	Issuer asn1.RawValue
	Serial *big.Int
}
type signerInfo struct {
	Version   int
	Signer    issuerSerial
	Digest    pkix.AlgorithmIdentifier
	Signed    []Attribute `asn1:"optional,tag:0,set"`
	Algorithm pkix.AlgorithmIdentifier
	Signature []byte
	Unsigned  []Attribute `asn1:"optional,tag:1,set"`
}
type signedData struct {
	Version      int
	Digests      []pkix.AlgorithmIdentifier `asn1:"set"`
	Content      contentInfo
	Certificates asn1.RawValue `asn1:"optional,tag:0"`
	CRLs         asn1.RawValue `asn1:"optional,tag:1"`
	Signers      []signerInfo  `asn1:"set"`
}

func algorithm(oid asn1.ObjectIdentifier) pkix.AlgorithmIdentifier {
	return pkix.AlgorithmIdentifier{Algorithm: oid, Parameters: asn1.RawValue{Tag: asn1.TagNull}}
}
func rawDER(value any) (asn1.RawValue, error) {
	data, err := asn1.Marshal(value)
	return asn1.RawValue{FullBytes: data}, err
}
func explicitContent(data []byte) asn1.RawValue {
	return asn1.RawValue{Class: asn1.ClassContextSpecific, Tag: 0, IsCompound: true, Bytes: data}
}

// SignDetached creates a CMS signature for id-data without embedding content.
// Attributes supplies format-specific signed attributes; mandatory digest and
// content-type attributes are generated by this function.
func SignDetached(ctx context.Context, identity Identity, content []byte, attributes []Attribute, options Options) ([]byte, error) {
	return signContent(ctx, identity, contentInfo{Type: oidData}, content, attributes, options)
}

// SignPKCS7 signs a DER-encoded value using the legacy PKCS#7 content-octet
// hashing rules required by Authenticode.
func SignPKCS7(ctx context.Context, identity Identity, contentType asn1.ObjectIdentifier, content []byte, attributes []Attribute, options Options) ([]byte, error) {
	var value asn1.RawValue
	if err := decodeDER(content, &value); err != nil {
		return nil, err
	}
	return signContent(ctx, identity, contentInfo{contentType, explicitContent(content)}, value.Bytes, attributes, options)
}
func signContent(ctx context.Context, identity Identity, content contentInfo, digestContent []byte, attributes []Attribute, options Options) ([]byte, error) {
	if err := validateIdentity(identity); err != nil {
		return nil, err
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	hash := sha256.Sum256(digestContent)
	contentType, err := rawDER(content.Type)
	if err != nil {
		return nil, err
	}
	digest, err := rawDER(hash[:])
	if err != nil {
		return nil, err
	}
	attrs := []Attribute{{oidContentType, []asn1.RawValue{contentType}}, {oidMessageDigest, []asn1.RawValue{digest}}}
	seen := map[string]bool{oidContentType.String(): true, oidMessageDigest.String(): true}
	for _, attr := range attributes {
		if seen[attr.Type.String()] || len(attr.Values) == 0 {
			return nil, errors.New("duplicate or empty signed CMS attribute")
		}
		seen[attr.Type.String()] = true
		attrs = append(attrs, attr)
	}
	encodedAttrs, err := asn1.MarshalWithParams(attrs, "set")
	if err != nil {
		return nil, err
	}
	attrDigest := sha256.Sum256(encodedAttrs)
	signature, err := identity.Signer.Sign(rand.Reader, attrDigest[:], crypto.SHA256)
	if err != nil {
		return nil, err
	}
	signer := signerInfo{Version: 1, Signer: issuerSerial{asn1.RawValue{FullBytes: identity.Certificate.RawIssuer}, identity.Certificate.SerialNumber}, Digest: algorithm(oidSHA256), Signed: attrs, Algorithm: algorithm(oidRSA), Signature: signature}
	if options.TimestampURL != "" {
		timestamp, err := requestTimestamp(ctx, signature, options)
		if err != nil {
			return nil, err
		}
		oid := options.TimestampAttribute
		if len(oid) == 0 {
			oid = oidRFC3161
		}
		signer.Unsigned = []Attribute{{oid, []asn1.RawValue{{FullBytes: timestamp}}}}
	}
	certificates := bytes.Clone(identity.Certificate.Raw)
	for _, cert := range identity.Chain {
		if cert == nil {
			return nil, errors.New("nil certificate in signing chain")
		}
		certificates = append(certificates, cert.Raw...)
	}
	data := signedData{Version: 1, Digests: []pkix.AlgorithmIdentifier{algorithm(oidSHA256)}, Content: content, Certificates: asn1.RawValue{Class: 2, Tag: 0, IsCompound: true, Bytes: certificates}, Signers: []signerInfo{signer}}
	encoded, err := asn1.Marshal(data)
	if err != nil {
		return nil, err
	}
	return asn1.Marshal(contentInfo{oidSignedData, explicitContent(encoded)})
}
