//go:build ignore

// generate-manifest-schema publishes the field reference directly from the
// closed HCL schema descriptor used by decoding and validation.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/wailsapp/wails/v3/internal/wake/manifest"
)

func main() {
	output := flag.String("output", "../docs/src/content/docs/reference/wails-hcl-fields.md", "generated Markdown output path, or - for stdout")
	flag.Parse()
	data := append([]byte("---\ntitle: wails.hcl fields\ndescription: Generated field, type, default and applicability reference for the Wails v3 HCL manifest.\n---\n\n<!-- Code generated by v3/scripts/generate-manifest-schema.go; DO NOT EDIT. -->\n\nFields are listed using schema paths. Labelled blocks use placeholders such as `target[\"target\"]` and `package[\"format\"]`.\n\n"), manifest.SchemaReferenceMarkdown()...)
	if *output == "-" {
		_, _ = os.Stdout.Write(data)
		return
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*output, data, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
